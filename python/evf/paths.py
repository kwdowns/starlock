"""Centralized path resolution: the repo (development) vs an installed release.

Repo:     the repo root, found by walking up from __file__ to pyproject.toml.
          Works on any OS, for development on a PC.
Release:  STARLOCK_ROOT (set by the starlock-headless launcher) names the
          install directory (/usr/lib/starlock-headless), laid out as
          camera_server, data/, marketing/.
"""

import os
import platform
from pathlib import Path

_ENV_ROOT = os.environ.get("STARLOCK_ROOT")
_RELEASE = _ENV_ROOT is not None

if _RELEASE:
    _RELEASE_ROOT = Path(_ENV_ROOT).resolve()
    _REPO_ROOT = None
else:
    _d = Path(__file__).resolve().parent
    while _d != _d.parent:
        if (_d / "pyproject.toml").exists():
            break
        _d = _d.parent
    _REPO_ROOT = _d
    _RELEASE_ROOT = None


def _data(release_rel: str, repo_rel: str) -> Path:
    return _RELEASE_ROOT / release_rel if _RELEASE else _REPO_ROOT / repo_rel


def tetra3rs_database_path() -> Path:
    """Path to the prebuilt tetra3rs SolverDatabase .bin.

    Generated by scripts/build_tetra3rs_catalog.py from the bundled
    gaia-catalog package; shipped in data/.
    """
    return _data("data/tetra3rs_gaia.bin", "data/tetra3rs_gaia.bin")


def version_json() -> Path:
    return _data("data/VERSION.json", "data/VERSION.json")


def minor_planets_json() -> Path:
    """Orbital elements of the bright asteroids (scripts/update_minor_planets.py)."""
    return _data("data/minor_planets.json", "data/minor_planets.json")


def sounds_dir() -> Path:
    return _data("data/sounds", "data/sounds")


def title_image() -> Path:
    return _data("marketing/inapp-title.png", "marketing/inapp-title.png")


def camera_binary() -> Path:
    """Path to the camera server binary.

    Release (the Pi package): camera_server in the install directory.
    Repo, for development: the platform's build under camera/ (Linux C/V4L2,
    Windows C/DirectShow, macOS Swift).

    Raises FileNotFoundError if the binary cannot be located.
    """
    if _RELEASE:
        p = _RELEASE_ROOT / "camera_server"
        hint = ""
    elif platform.system() == "Linux":
        p = _REPO_ROOT / "camera" / "linux" / "camera_server"
        hint = " — run make -C camera/linux"
    elif platform.system() == "Windows":
        p = _REPO_ROOT / "camera" / "windows" / "camera_server.exe"
        hint = r" — run camera\windows\build.bat"
    else:
        p = _REPO_ROOT / "camera" / "mac" / "camera_server"
        hint = " — run scripts/build_camera_mac.sh"
    if p.exists():
        return p
    raise FileNotFoundError(f"Cannot find camera_server at {p}{hint}")


def web_dist_dir() -> Path:
    """The built React app: data/web_dist in a release, web/dist after `npm run build`."""
    return _data("data/web_dist", "web/dist")


def catalog_data_dir() -> Path:
    """The web UI's catalog JSON (objects, openngc, hyg-bright), served to apps.

    In the repo they live in web/src/data/; release builds copy them to
    data/web_catalog/.
    """
    return _data("data/web_catalog", "web/src/data")


def samples_dir() -> Path | None:
    """Path to test sample images, for the DebugPanel's sample injection
    (STARLOCK_DEBUG=1). None if the directory is missing.
    """
    p = _data("data/samples", "tests/samples")
    return p if p.exists() else None
